"""Builds the printables for the graduation gift from src/gift_config.h:

- print/gift_label.svg/.pdf: the 60 x 25 mm "culture label" sticker
  (GIFT_NAME, GIFT_DEGREE, GIFT_DATE).
- print/gift_card.svg/.pdf: an 85 x 55 mm how-to card (first-start Wi-Fi steps
  with GIFT_SETUP_NETWORK, and what the buttons do). Its wording is in
  build_card() below.

PDFs are written when cairosvg is installed.

Usage, from the firmware folder:
    python3 tools/make_gift_label.py
PDF output needs `pip install cairosvg` (and the Cairo library, e.g.
`brew install cairo`). Without it only the SVG is written.

Size: each page is the printed piece plus 1 mm on every side: the background
runs 1 mm past the solid grey cut line, so a slightly off cut leaves no white
edge. Print at 100 % / "actual size", never "fit to page".
"""
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONFIG = ROOT / "src" / "gift_config.h"
OUT_DIR = ROOT.parent / "print"

LABEL_W, LABEL_H, BLEED = 60.0, 25.0, 1.0
PAGE_W, PAGE_H = LABEL_W + 2 * BLEED, LABEL_H + 2 * BLEED

SANS = "'Helvetica Neue', Helvetica, Arial, sans-serif"
MONO = "Menlo, 'DejaVu Sans Mono', Consolas, 'Courier New', monospace"
INK, MUTED, RULE = "#1D1830", "#6E6690", "#1D1830"
STRIP = "#EFEBFA"
# Same palette as the on-screen logo (src/ui.cpp), with a darker rim for paper.
GLASS, AGAR, SHINE = "#8F82C9", "#E8A94E", "#F6D396"
CREAM, ROSE, LILAC = "#FFF3DC", "#F27E95", "#9E84F5"
COLONIES = [(-0.30, -0.22, 0.17, CREAM), (0.30, -0.36, 0.10, ROSE), (0.40, 0.12, 0.14, LILAC),
            (-0.08, 0.40, 0.12, CREAM), (-0.47, 0.22, 0.08, ROSE), (0.08, 0.00, 0.07, LILAC),
            (0.30, 0.46, 0.06, ROSE)]


def read_config():
    text = CONFIG.read_text(encoding="utf-8")
    values = {}
    for key in ("GIFT_NAME", "GIFT_DEGREE", "GIFT_DATE", "GIFT_SETUP_NETWORK"):
        match = re.search(rf'{key}\[\]\s*=\s*"((?:[^"\\]|\\.)*)"', text)
        if not match:
            sys.exit(f"{key} not found in {CONFIG}")
        values[key] = match.group(1).encode("utf-8").decode("unicode_escape").encode(
            "latin-1").decode("utf-8")
    return values


def fit(text, size, room, advance):
    """Font size that keeps `text` within `room` mm (advance = width per em per char)."""
    width = len(text) * advance * size
    return round(min(size, size * room / width), 2) if width else size


def dish(cx, cy, r):
    unit = r / 26.0
    agar = r - 4.5 * unit
    shine_r = agar - 3.5 * unit
    parts = [
        f'<circle cx="{cx}" cy="{cy}" r="{r - 1.2 * unit:.3f}" fill="{STRIP}" '
        f'stroke="{GLASS}" stroke-width="{2.4 * unit:.3f}"/>',
        f'<circle cx="{cx}" cy="{cy}" r="{agar:.3f}" fill="{AGAR}"/>',
        # Reflection on the upper left, like the arc on screen.
        f'<path d="M {cx - shine_r * 0.966:.3f} {cy - shine_r * 0.259:.3f} '
        f'A {shine_r:.3f} {shine_r:.3f} 0 0 1 {cx - shine_r * 0.259:.3f} {cy - shine_r * 0.966:.3f}" '
        f'fill="none" stroke="{SHINE}" stroke-width="{2.0 * unit:.3f}" stroke-linecap="round"/>',
    ]
    for dx, dy, cr, colour in COLONIES:
        parts.append(f'<circle cx="{cx + dx * r:.3f}" cy="{cy + dy * r:.3f}" '
                     f'r="{cr * r:.3f}" fill="{colour}"/>')
    return "\n    ".join(parts)


def build_svg(name, degree, date):
    x0, y0 = BLEED, BLEED            # label corner
    strip_w = 14.0
    left = x0 + strip_w + 2.0        # text column
    right = x0 + LABEL_W - 2.0
    key_w = 8.2                      # room for "DEGREE"
    name_size = fit(name, 4.2, right - left, 0.62)
    value_room = right - left - key_w
    rows = [("DEGREE", degree), ("DATE", date), ("STRAIN", "Graduate, viable")]
    value_size = min(fit(value, 2.3, value_room, 0.602) for _, value in rows)
    esc = lambda s: html.escape(s, quote=True)

    row_svg = []
    for index, (key, value) in enumerate(rows):
        y = y0 + 14.0 + index * 3.6
        row_svg.append(
            f'<text x="{left}" y="{y:.2f}" font-family="{MONO}" font-size="1.75" fill="{MUTED}" '
            f'letter-spacing="0.08">{key}</text>\n    '
            f'<text x="{left + key_w}" y="{y:.2f}" font-family="{MONO}" font-size="{value_size}" '
            f'fill="{INK}">{esc(value)}</text>')

    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by firmware/tools/make_gift_label.py from src/gift_config.h. -->
<!-- Label 60 x 25 mm; page 62 x 27 mm with 1 mm bleed. Cut on the grey line. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{PAGE_W:g}mm" height="{PAGE_H:g}mm"
     viewBox="0 0 {PAGE_W:g} {PAGE_H:g}">
  <title>Culture label: {esc(name)}</title>
  <!-- Background runs into the bleed. -->
  <rect x="0" y="0" width="{PAGE_W:g}" height="{PAGE_H:g}" fill="#FFFFFF"/>
  <rect x="0" y="0" width="{x0 + strip_w:g}" height="{PAGE_H:g}" fill="{STRIP}"/>
  <line x1="{x0 + strip_w:g}" y1="0" x2="{x0 + strip_w:g}" y2="{PAGE_H:g}" stroke="{RULE}" stroke-width="0.12"/>
  <g id="dish">
    {dish(x0 + strip_w / 2, y0 + LABEL_H / 2, 5.4)}
  </g>
  <g id="fields">
    <text x="{left}" y="{y0 + 3.6:.2f}" font-family="{MONO}" font-size="1.6" fill="{MUTED}" letter-spacing="0.12">CULTURE</text>
    <text x="{right}" y="{y0 + 3.6:.2f}" font-family="{MONO}" font-size="1.6" fill="{MUTED}" text-anchor="end" letter-spacing="0.12">No. 001</text>
    <text x="{left}" y="{y0 + 8.4:.2f}" font-family="{SANS}" font-size="{name_size}" font-weight="700" fill="{INK}">{esc(name)}</text>
    <line x1="{left}" y1="{y0 + 10.2:.2f}" x2="{right}" y2="{y0 + 10.2:.2f}" stroke="{RULE}" stroke-width="0.2"/>
    {chr(10).join("    " + r if i else r for i, r in enumerate(row_svg))}
    <line x1="{left}" y1="{y0 + 22.4:.2f}" x2="{right}" y2="{y0 + 22.4:.2f}" stroke="{RULE}" stroke-width="0.1"/>
  </g>
  <!-- Cut line: exactly the 60 x 25 mm label edge. -->
  <rect id="cut-line" x="{x0:g}" y="{y0:g}" width="{LABEL_W:g}" height="{LABEL_H:g}" rx="1"
        fill="none" stroke="#9A9A9A" stroke-width="0.1"/>
</svg>
'''


# Which physical button does what, as the firmware maps them: GPIO 0 (BOOT) is
# next screen, GPIO 14 is messages. Check "lower"/"upper" on the real board
# before printing.
NEXT_SCREEN_BUTTON, MESSAGE_BUTTON = "LOWER", "UPPER"


def build_card(name, network):
    card_w, card_h = 85.0, 55.0
    page_w, page_h = card_w + 2 * BLEED, card_h + 2 * BLEED
    x0, y0 = BLEED, BLEED
    left, right = x0 + 4.0, x0 + card_w - 4.0
    room = right - left
    esc = lambda s: html.escape(s, quote=True)
    band = 14.0

    def mono(x, y, value, size, colour=INK, extra=""):
        return (f'<text x="{x:.2f}" y="{y:.2f}" font-family="{MONO}" font-size="{size}" '
                f'fill="{colour}"{extra}>{esc(value)}</text>')

    def heading(y, value):
        return mono(left, y, value, 1.7, MUTED, ' letter-spacing="0.14"')

    steps = ["1  Plug it in with a USB-C cable.",
             f'2  On your phone, join Wi-Fi "{network}".',
             "3  Choose your home Wi-Fi on the page that opens."]
    step_size = min(fit(step, 2.1, room, 0.602) for step in steps)
    key_w = 10.0
    buttons = [(NEXT_SCREEN_BUTTON, "press: next screen"),
               (MESSAGE_BUTTON, "press: messages \u00b7 hold: mark as read"),
               ("BOTH", "hold together 3 s: Wi-Fi setup again")]
    button_size = min(fit(text, 2.0, room - key_w, 0.602) for _, text in buttons)

    parts = [heading(y0 + band + 4.6, "FIRST START")]
    for index, step in enumerate(steps):
        parts.append(mono(left, y0 + band + 8.2 + index * 3.3, step, step_size))
    parts.append(mono(left + 3 * step_size * 0.602, y0 + band + 8.2 + 3 * 3.3 - 0.4,
                      "(no page? open 192.168.4.1)", 1.7, MUTED))
    rule_y = y0 + band + 21.6
    parts.append(f'<line x1="{left}" y1="{rule_y:.2f}" x2="{right}" y2="{rule_y:.2f}" '
                 f'stroke="{RULE}" stroke-width="0.12"/>')
    parts.append(heading(rule_y + 4.0, "BUTTONS"))
    for index, (key, text) in enumerate(buttons):
        y = rule_y + 7.6 + index * 3.3
        parts.append(mono(left, y, key, 1.75, MUTED, ' letter-spacing="0.08"'))
        parts.append(mono(left + key_w, y, text, button_size))
    body = "\n    ".join(parts)

    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by firmware/tools/make_gift_label.py from src/gift_config.h. -->
<!-- Card 85 x 55 mm; page 87 x 57 mm with 1 mm bleed. Cut on the grey line. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{page_w:g}mm" height="{page_h:g}mm"
     viewBox="0 0 {page_w:g} {page_h:g}">
  <title>How to use your display</title>
  <rect x="0" y="0" width="{page_w:g}" height="{page_h:g}" fill="#FFFFFF"/>
  <rect x="0" y="0" width="{page_w:g}" height="{y0 + band:g}" fill="{STRIP}"/>
  <line x1="0" y1="{y0 + band:g}" x2="{page_w:g}" y2="{y0 + band:g}" stroke="{RULE}" stroke-width="0.12"/>
  <g id="dish">
    {dish(left + 4.6, y0 + band / 2, 4.6)}
  </g>
  <text x="{left + 12:.2f}" y="{y0 + 6.6:.2f}" font-family="{SANS}" font-size="{fit("How to use your display", 3.6, room - 12, 0.58)}" font-weight="700" fill="{INK}">How to use your display</text>
  {mono(left + 12, y0 + 10.4, "for " + name, fit("for " + name, 2.0, room - 12, 0.602), MUTED)}
  <g id="instructions">
    {body}
  </g>
  <rect id="cut-line" x="{x0:g}" y="{y0:g}" width="{card_w:g}" height="{card_h:g}" rx="3"
        fill="none" stroke="#9A9A9A" stroke-width="0.1"/>
</svg>
'''


def write(stem, svg):
    OUT_DIR.mkdir(exist_ok=True)
    svg_path = OUT_DIR / f"{stem}.svg"
    svg_path.write_text(svg, encoding="utf-8")
    print(f"wrote {svg_path}")
    try:
        import cairosvg
    except ImportError:
        print("cairosvg not installed: PDF not written (pip install cairosvg)")
        return
    pdf_path = OUT_DIR / f"{stem}.pdf"
    cairosvg.svg2pdf(bytestring=svg.encode("utf-8"), write_to=str(pdf_path))
    print(f"wrote {pdf_path}")


def main():
    values = read_config()
    write("gift_label", build_svg(values["GIFT_NAME"], values["GIFT_DEGREE"], values["GIFT_DATE"]))
    write("gift_card", build_card(values["GIFT_NAME"], values["GIFT_SETUP_NETWORK"]))


if __name__ == "__main__":
    main()
