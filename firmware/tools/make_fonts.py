"""Builds TFT_eSPI smooth-font (.vlw layout) arrays from M PLUS Rounded 1c.

Usage: put MPLUSRounded1c-{Medium,Bold,ExtraBold}.ttf next to this script, renamed
MPR-Medium.ttf, MPR-Bold.ttf and MPR-ExtraBold.ttf, then run
    python3 make_fonts.py ../src/fonts.h
Needs the freetype-py package.
"""
import freetype, struct, sys
GREEK = [chr(c) for c in range(0x386, 0x3CF) if c not in (0x387, 0x38B, 0x38D, 0x3A2)]
TEXT = [chr(c) for c in range(0x21, 0x7F)] + list("°·«»€…–—’‘“”") + GREEK
FONTS = [  # name, file, pixel size, characters
    ("FONT_CLOCK", "MPR-ExtraBold.ttf", 88, list("0123456789:-")),
    ("FONT_TEMP",  "MPR-ExtraBold.ttf", 66, list("0123456789-°")),
    ("FONT_VALUE", "MPR-Bold.ttf",      22, list("0123456789-°:./") ),
    # Greek is included so a Greek name works on the welcome screen (src/gift_config.h).
    ("FONT_TITLE", "MPR-ExtraBold.ttf", 26, [chr(c) for c in range(0x21, 0x7F)] + GREEK),
    ("FONT_TEXT",  "MPR-Medium.ttf",    15, TEXT),
    # Larger body text for the Messages screen.
    ("FONT_MESSAGE", "MPR-Medium.ttf",  20, TEXT),
]
def build(path, size, chars):
    face = freetype.Face(path); face.set_pixel_sizes(0, size)
    def metric(ch):
        face.load_char(ch, freetype.FT_LOAD_RENDER); return face.glyph.bitmap_top, face.glyph.bitmap.rows
    # Digit-only fonts: use the digit box so centring works on the numerals themselves.
    ref_up, ref_down = ('d', 'p') if 'd' in chars else ('0', '0')
    top, rows = metric(ref_up); ascent = top
    top2, rows2 = metric(ref_down); descent = max(0, rows2 - top2)
    table, bitmaps = b"", b""; count = 0
    for ch in chars:
        if face.get_char_index(ord(ch)) == 0: continue
        face.load_char(ch, freetype.FT_LOAD_RENDER)
        g = face.glyph; bm = g.bitmap
        assert bm.width <= 255 and bm.rows <= 255 and (g.advance.x >> 6) <= 255
        data = bytearray()
        for y in range(bm.rows): data += bytes(bm.buffer[y * bm.pitch: y * bm.pitch + bm.width])
        table += struct.pack(">7i", ord(ch), bm.rows, bm.width, g.advance.x >> 6, g.bitmap_top, g.bitmap_left, 0)
        bitmaps += bytes(data); count += 1
    return struct.pack(">6i", count, 11, size, 0, ascent, descent) + table + bitmaps + b"\x00\x00\x00\x00\x01", count
out = ["// Generated by tools/make_fonts.py from M PLUS Rounded 1c",
       "// (Copyright 2016 The Rounded M+ Project Authors, SIL Open Font License 1.1).",
       "// Layout: TFT_eSPI smooth font (.vlw). Do not edit by hand.", "#pragma once", "", "#include <Arduino.h>", ""]
for name, path, size, chars in FONTS:
    blob, count = build(path, size, chars)
    open(name + ".vlw", "wb").write(blob)
    out.append(f"// {path.replace('MPR-', 'MPLUSRounded1c-')} at {size} px, {count} glyphs, {len(blob)} bytes")
    out.append(f"const uint8_t {name}[] PROGMEM = {{")
    for i in range(0, len(blob), 24): out.append("  " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    out.append("};"); out.append("")
    print(name, count, "glyphs", len(blob), "bytes", file=sys.stderr)
open(sys.argv[1], "w").write("\n".join(out))
